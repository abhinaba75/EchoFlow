package com.example.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Material 3 layout spacing scale (4dp base grid). Using one shared scale across every screen is
 * what gives the redesign rhythmic, cohesive spacing instead of ad-hoc padding values.
 */
object Spacing {
    val xs = 4.dp
    val s = 8.dp
    val m = 12.dp
    val base = 16.dp   // page margin / standard padding
    val l = 20.dp
    val xl = 24.dp     // section gap
    val xxl = 32.dp
    val huge = 48.dp
}
